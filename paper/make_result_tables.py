"""Result tables of the paper (LaTeX), built from the summary files in results/.

Writes paper/tables/tab_variants.tex (Table 3), tab_passes.tex (Table 4) and tab_h3.tex (Table 5),
and two tables whose numbers the paper gives in its text: tab_control.tex (error of the daily
cooling energy for each control pattern) and tab_robust.tex (material changes with every threshold
halved and doubled).
Usage (repository root): python3 paper/make_result_tables.py
"""
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
OUT = Path(__file__).resolve().parent / "tables"
RES = REPO / "results"


def table(label, caption, colspec, header, rows, note=""):
    lines = [
        "% Generated by make_result_tables.py. Do not edit.",
        "\\begin{table}[tbp]",
        "  \\centering",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        f"  \\begin{{tabularx}}{{\\textwidth}}{{{colspec}}}",
        "    \\toprule",
        f"    {header} \\\\",
        "    \\midrule",
        *[f"    {r} \\\\" for r in rows],
        "    \\bottomrule",
        "  \\end{tabularx}",
    ]
    if note:
        lines += ["  \\par\\smallskip\\raggedright", f"  {note}"]
    lines.append("\\end{table}")
    return "\n".join(lines) + "\n"


def variants():
    d = pd.read_csv(RES / "single_room/room_variants.csv")
    d = d[d["var"] == "Zone Mean Air Temperature"]
    order = d.pivot(index="variant", columns="configuration", values="order")
    err = d.pivot(index="variant", columns="configuration", values="rms_ts04_C")
    # Orders estimated without a reference (three runs, each timestep half the last)
    o = pd.read_csv(RES / "order_estimates/order_estimates.csv")
    o = o[(o["source"] == "room_variants") & (o["variable"] == "air") & (o["method"] == "three_level")]

    def free(k, c, window):
        r = o[(o["case"] == f"free_nosolar:{k}") & (o["configuration"] == c)
              & (o["window"] == window)]
        assert len(r) == 1, (k, c, window)
        return f"{r['order'].iloc[0]:.2f}"

    names = [
        ("unchanged", "As described"),
        ("fixed_h", "Interior convection fixed at \\SI{3}{W/(m^2.K)}"),
        ("no_lw", "Interior long-wave exchange off"),
        ("fixed_h_no_lw", "Both of the above"),
        ("long_warmup", "100 warmup days"),
    ]
    groups = [
        ("release", "Release"),
        ("inside_faces", "Inside faces calculated again until the surfaces and air agree"),
        ("both_faces", "Both faces calculated again until the surfaces and air agree"),
    ]
    rows = []
    for g, (c, head) in enumerate(groups):
        if g:
            rows.append("\\addlinespace")
        rows.append(f"\\multicolumn{{5}}{{@{{}}l}}{{\\emph{{{head}}}}}")
        rows += [f"{lab} & {order.loc[k, c]:.2f} & {free(k, c, '3/6/12/h')} & "
                 f"{free(k, c, '5/10/20/h')} & {err.loc[k, c]:.4f}" for k, lab in names]
    header = (
        "\\multicolumn{1}{@{}l}{Variant} & Fitted order & \\multicolumn{2}{c}{Order without a reference} "
        "& RMS error (\\si{\\celsius}) \\\\\n    \\cmidrule(lr){3-4}\n"
        "    \\multicolumn{1}{@{}l}{\\emph{Timesteps per hour}} & 2--10, against 30 & 3, 6, 12 & 5, 10, 20 & 4"
    )
    t = table(
        "tab:variants",
        "Order of accuracy and error of the zone air temperature in the single room floating on its "
        "summer design day, with the default third-order scheme, for variants that change one term "
        "of the model.",
        "@{}>{\\raggedright\\arraybackslash\\leftskip=1em}p{0.37\\textwidth}"
        "*{4}{>{\\centering\\arraybackslash}X}@{}",
        header,
        rows,
        "Order 1: the error halves when the timestep is halved. Order 2: it falls fourfold.",
    )
    # \addlinespace is a spacing command, not a table row
    return t.replace("\\addlinespace \\\\", "\\addlinespace")


def passes():
    a = pd.read_csv(RES / "passes/pass_limits_room.csv")
    a = a[a["case"] == "free"].set_index("setting")
    o = pd.read_csv(RES / "passes/pass_limits_office.csv").set_index("setting")
    rel = o.loc["release", "wall_s"]
    spec = [
        ("passes_1", "One pass", "1"),
        ("passes_2", "Two passes", "2"),
        ("tol_1e-3", "Passes until the air changes by less than \\SI{0.001}{\\celsius}", None),
        ("converged", "Converged", None),
    ]
    rows = []
    for key, lab, npass in spec:
        mean = npass or f"{a.loc[key, 'mean_passes']:.1f}"
        err = a.loc[key, "iteration_error_C"]
        err_s = "--" if key == "converged" else f"{err:.4f}"
        rows.append(f"{lab} & {mean} & {err_s} & {o.loc[key, 'wall_s']:.1f} & "
                    f"{o.loc[key, 'wall_s'] / rel:.2f}")
    note = (f"Passes and difference: single room, free-floating, summer design day, four timesteps "
            f"per hour. For comparison, the converged solution differs from its own run with 30 "
            f"timesteps per hour by \\SI{{{a['timestep_error_converged_C'].iloc[0]:.4f}}}{{\\celsius}}, "
            f"and the release differs from that run by "
            f"\\SI{{{a['release_error_C'].iloc[0]:.3f}}}{{\\celsius}}. Runtime: annual run of the "
            f"small office distributed with EnergyPlus, release {rel:.1f}~s, one sample each. Extra "
            f"passes: the mean number of additional calculations of the surfaces, air and HVAC per "
            f"timestep.")
    return table(
        "tab:passes",
        "Mean extra passes per timestep, difference from the converged solution and runtime for "
        "each limit on the passes.",
        "@{}Ycccc@{}",
        "Limit & Extra passes & Difference (\\si{\\celsius}) & Runtime (s) & Ratio to release",
        rows,
        note,
    )


def control():
    d = pd.read_csv(RES / "single_room/control_patterns.csv")
    d = d[d["day"] == "CLG"].pivot(index="pattern", columns="configuration", values="rel_err_ts04")
    names = [
        ("always_constant", "Always controlled at \\SI{22}{\\celsius}"),
        ("band_constant", "Floating in a band of 21 to \\SI{22}{\\celsius}"),
        ("band_stepped", "Band of 21 to \\SI{24}{\\celsius} by day, 15 to \\SI{30}{\\celsius} at night"),
        ("always_step2", "Always controlled, step from 22 to \\SI{20}{\\celsius} from 08:00 to 18:00"),
        ("always_step2_nosub", "The same step, subdivision of the HVAC timestep suppressed"),
    ]
    rows = [f"{lab} & {100 * d.loc[k, 'release']:.1f} & {100 * d.loc[k, 'converged']:.2f}"
            for k, lab in names]
    return table(
        "tab:control",
        "Error of the daily cooling energy of the ideal air system at four timesteps per hour, with "
        "the release and with the surfaces, air and HVAC in agreement, for each control "
        "pattern.",
        "@{}Ycc@{}",
        "Control pattern & Release (\\%) & Balances in agreement (\\%)",
        rows,
        "Single room without solar gain, summer design day, against the run with 30 timesteps per "
        "hour of the same configuration. Balances in agreement: the surfaces, air and HVAC calculated "
        "again within each timestep until they agree.",
    )


def h3():
    h = pd.read_csv(RES / "prototypes/outcome_counts.csv")
    m = pd.read_csv(RES / "prototypes/accuracy_runtime_summary.csv")
    count = h.pivot(index="outcome", columns="configuration", values="material_cases")
    elig = h[h["configuration"] == "two_passes"].set_index("outcome")
    names = [
        ("energy", "Annual heating, cooling or fan energy", "at least 1\\%"),
        ("peak_demand", "Annual peak electric demand", "at least 2\\%"),
        ("unmet_hours", "Occupied unmet hours", "10\\% and 5~h, or 300~h"),
        ("autosized_capacities", "Autosized capacity", "at least 2\\%"),
        ("window_savings", "Savings of the window upgrade", "10\\%, or sign"),
    ]
    rows = []
    for k, lab, thr in names:
        verdict = "yes" if bool(elig.loc[k, "supported"]) else "no"
        rows.append(f"{lab} & {int(elig.loc[k, 'eligible_cases'])} & {int(count.loc[k, 'one_pass'])} & "
                    f"{int(count.loc[k, 'two_passes'])} & {int(count.loc[k, 'converged'])} & {verdict}")
    air = m[m["measure"] == "air_rms_C"]
    met = int((air["ratio"] >= 2).sum())
    rows.append(f"Accuracy at half the runtime & {len(air)} buildings & "
                f"-- & {met} & -- & no")
    return table(
        "tab:h3",
        "Cases in which each outcome changed materially, with each corrected configuration, and the "
        "verdict on hypothesis H3 for two passes.",
        "@{}Yccccc@{}",
        "Outcome & Cases & One pass & Two passes & Converged & Supported",
        rows,
        "Cases: the eligible cases. One pass, two passes, converged: the cases that change "
        "materially, with the thresholds of Table~\\ref{tab:thresholds}. Supported: at least a quarter "
        "of the cases change materially with two passes. Accuracy at half the runtime: the buildings in "
        "which the release needs at least twice the runtime of two passes at four timesteps per hour to "
        "reach their error in hourly air temperature.",
    )


def robustness():
    import numpy as np
    d = pd.read_csv(RES / "prototypes/case_deltas.csv")
    d = d[d["configuration"] == "two_passes"]

    def energy(t):
        m = np.zeros(len(d), bool)
        for c, e in [("heating_pct", "heating_eligible"), ("cooling_pct", "cooling_eligible"),
                     ("fans_pct", "fans_eligible")]:
            m |= d[e].astype(bool).values & (d[c].abs().values >= t)
        return int(m.sum())

    cap = d[["cool_cap_W_pct", "heat_cap_W_pct", "fan_flow_m3s_pct"]].abs().max(axis=1)
    s = d[d["window_savings_eligible"].astype(bool)]
    sign = np.sign(s["savings_release_GJ"]) != np.sign(s["savings_corrected_GJ"])

    def unmet(f):
        # the 10% / 5 h test scaled by f for heating and cooling, and the 300 h crossing kept
        rows = []
        for _, r in d.iterrows():
            hit = False
            for a, b in [("unmet_heat_release", "unmet_heat_corrected"), ("unmet_cool_release", "unmet_cool_corrected")]:
                dv = abs(r[b] - r[a])
                hit |= r[a] > 0 and dv >= 0.10 * f * r[a] and dv >= 5 * f
            tr = r["unmet_heat_release"] + r["unmet_cool_release"]
            tf = r["unmet_heat_corrected"] + r["unmet_cool_corrected"]
            hit |= (tr > 300) != (tf > 300)
            rows.append(hit)
        return int(sum(rows))

    rows = [
        f"Annual heating, cooling or fan energy & 45 & {energy(0.5)} & {energy(1)} & {energy(2)}",
        f"Annual peak electric demand & 45 & {int((d['peak_pct'].abs() >= 1).sum())} & "
        f"{int((d['peak_pct'].abs() >= 2).sum())} & {int((d['peak_pct'].abs() >= 4).sum())}",
        f"Occupied unmet hours & 45 & {unmet(0.5)} & {unmet(1)} & {unmet(2)}",
        f"Autosized capacity & 45 & {int((cap >= 1).sum())} & {int((cap >= 2).sum())} & "
        f"{int((cap >= 4).sum())}",
        f"Savings of the window upgrade & {len(s)} & "
        f"{int(((s['savings_pct'].abs() >= 5) | sign).sum())} & "
        f"{int(((s['savings_pct'].abs() >= 10) | sign).sum())} & "
        f"{int(((s['savings_pct'].abs() >= 20) | sign).sum())}",
    ]
    return table(
        "tab:robust",
        "Cases that change materially with two passes when every threshold is halved, as set, and "
        "doubled.",
        "@{}Ycccc@{}",
        "Outcome & Cases & Half & As set & Double",
        rows,
        "A quarter of the cases is 12 of 45, or 9 of 34 for the window upgrade. For unmet hours, the "
        "relative and absolute parts of the threshold are scaled, and the 300~h limit is kept.",
    )


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    for name, text in [("tab_variants", variants()), ("tab_passes", passes()),
                       ("tab_control", control()), ("tab_h3", h3()), ("tab_robust", robustness())]:
        (OUT / f"{name}.tex").write_text(text)
    print("written: tab_variants.tex, tab_passes.tex, tab_control.tex, tab_h3.tex, tab_robust.tex")
